"""
Draw the mark, once, so the icon and the window cannot disagree about it.

The glyph is the same one it has always been -- a circle that does not close,
with an arrow going back round it -- but drawn as a fan of fine straight lines
rather than as a stroke. Each line runs from the inner edge to the outer edge
with a twist on it, and where the lines crowd they read as solid while the
edges feather into caustics. Nothing is shaded; it is all one hairline.

Writes two files and is the only thing that should ever edit either:
  app/renderer/logo-art.ts   the strokes, for the window
  app/build/icon.html        the application icon, framed by a meander
"""
import math

SIZE = 1024
CX, CY = 512.0, 512.0
R_IN, R_OUT = 158.0, 262.0

# Angles are screen angles: 0 is three o'clock and they increase clockwise,
# because y runs down. The opening faces right, between one and four o'clock,
# and the sweep runs the other way round to finish at the lower right -- which
# is where the arrow is, and why it reads as coming back rather than going on.
START = math.radians(300.0)
END = math.radians(60.0)
FORWARD = -1.0 if END < START else 1.0

LINES = 480
TWIST = 0.34          # radians the outer end leads the inner end by
COUNTER = -0.17       # a lighter fan the other way, so the body has weight


#: How much of the sweep, at the arrow end, the twist fades out over.
SETTLE = 0.09


def arc(count: int, twist: float):
    """
    One fan of lines from the inner arc to the outer arc.

    The twist is what makes the band feather -- every line leans, so the two
    edges are envelopes rather than circles. It fades to nothing over the last
    stretch before the arrow, because a fan still leaning when it arrives
    throws hairlines out past the arrowhead and they read as a fray.
    """
    out = []
    for index in range(count):
        along = index / (count - 1)
        angle = START + (END - START) * along
        lean = twist * min(1.0, (1.0 - along) / SETTLE)
        x1 = CX + R_IN * math.cos(angle)
        y1 = CY + R_IN * math.sin(angle)
        x2 = CX + R_OUT * math.cos(angle + lean)
        y2 = CY + R_OUT * math.sin(angle + lean)
        out.append((x1, y1, x2, y2))
    return out


def strokes():
    return arc(LINES, TWIST) + arc(LINES // 2, COUNTER)


def at(radius: float, angle: float):
    return (CX + radius * math.cos(angle), CY + radius * math.sin(angle))


def arrowhead() -> str:
    """
    Solid, at the end of the sweep, pointing the way the sweep was going.

    The one filled shape in the mark, and the whole reason it reads as coming
    back round rather than as a letter -- so it has to survive at sixteen
    pixels, where every hairline has already gone.
    """
    tip = at((R_IN + R_OUT) / 2, END + FORWARD * 0.32)
    points = [tip, at(R_IN - 30, END), at(R_OUT + 30, END)]
    return " ".join(f"{x:.1f},{y:.1f}" for x, y in points)


def ts() -> str:
    rows = ",\n".join(
        f"  [{x1:.1f}, {y1:.1f}, {x2:.1f}, {y2:.1f}]" for x1, y1, x2, y2 in strokes()
    )
    return f'''/**
 * The mark, as line segments in a 0-{SIZE} box.
 *
 * GENERATED by app/build/make-logo.py. Edit that, not this.
 *
 * Coordinates rather than a path so the window and the application icon are
 * drawn from the same numbers; a logo that is traced twice is a logo that
 * drifts.
 */

/** x1, y1, x2, y2. */
export type Stroke = readonly [number, number, number, number];

export const BOX = {SIZE};

export const ARROWHEAD = "{arrowhead()}";

export const STROKES: readonly Stroke[] = [
{rows},
];
'''


def icon_html() -> str:
    lines = "\n".join(
        f'      <line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" />'
        for x1, y1, x2, y2 in strokes()
    )
    return f'''<!doctype html>
<meta charset="utf-8" />
<style>
  html, body {{ margin: 0; background: transparent; }}
  svg {{ display: block; }}
</style>
<!--
  GENERATED by app/build/make-logo.py. Edit that, not this.

  The application icon: the mark, framed by a meander -- one line that turns
  back on itself without ever breaking, which is roughly what the name means.
-->
<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}">
  <defs>
    <linearGradient id="ground" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#6b1725" />
      <stop offset="1" stop-color="#460e18" />
    </linearGradient>
    <!-- The band is exactly eight tiles across and one deep, and the pattern is
         moved to start on its corner, so no glyph is ever cut in half. -->
    <pattern id="meander" width="91" height="91" patternUnits="userSpaceOnUse"
             patternTransform="translate(148 148)">
      <g fill="none" stroke="#f6e9e5" stroke-width="5.5" opacity="0.55">
        <path d="M16 76 V24 H68 V60 H40 V42 H54" />
      </g>
    </pattern>
  </defs>

  <!-- macOS insets its icons; 100 of 1024 a side is the usual ratio. -->
  <rect x="100" y="100" width="824" height="824" rx="185" ry="185" fill="url(#ground)" />

  <!-- A square band of meander, one tile deep, around a plain thin frame. Cut
       with a mask rather than four strips so the corners meet properly. -->
  <mask id="band">
    <rect x="148" y="148" width="728" height="728" fill="white" />
    <rect x="239" y="239" width="546" height="546" fill="black" />
  </mask>
  <rect x="148" y="148" width="728" height="728" fill="url(#meander)" mask="url(#band)" />
  <rect x="247" y="247" width="530" height="530" fill="none" stroke="#f6e9e5"
        stroke-width="3" opacity="0.40" />

  <g transform="translate(512 512) scale(0.56) translate(-512 -512)">
    <g stroke="#f6e9e5" stroke-width="1.8" opacity="0.52" fill="none" stroke-linecap="round">
{lines}
    </g>
    <polygon points="{arrowhead()}" fill="#f6e9e5" />
  </g>
</svg>
'''


open("app/renderer/logo-art.ts", "w").write(ts())
open("app/build/icon.html", "w").write(icon_html())
print("logo-art.ts and icon.html written")
